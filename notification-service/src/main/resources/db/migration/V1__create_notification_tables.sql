-- Idempotency ledger: one row per successfully processed event.
CREATE TABLE processed_events (
    event_id      UUID PRIMARY KEY,
    order_id      UUID NOT NULL,
    processed_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Record of notifications handed to the delivery channel (demo stand-in for email/SMS).
CREATE TABLE notification_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     UUID         NOT NULL,
    order_id     UUID         NOT NULL,
    customer_id  VARCHAR(64)  NOT NULL,
    channel      VARCHAR(16)  NOT NULL,
    message      VARCHAR(512) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_notification_log_order_id ON notification_log (order_id);
